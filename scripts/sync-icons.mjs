// Copy the Continuity icons and AI provider marks from a StuntKit checkout into
// src/components/icon-gallery-data.ts, for the previews on /stuntkit/icons.
// Like src/components/icons.tsx, the geometry is owned by StuntKit: change it
// there first, then run this.
//
//   node scripts/sync-icons.mjs ../stuntkit

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'src/components/icon-gallery-data.ts');

/** The elements inside an SVG file's root `<svg>`, on one line. */
export function svgInner(svg) {
  const m = /<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg.trim());
  if (!m) throw new Error('not an SVG file');
  return m[1]
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('');
}

/** The data module, from the package's `svg/` directory. */
export function buildModule(svgDir) {
  const manifest = JSON.parse(readFileSync(join(svgDir, 'icons.json'), 'utf8'));
  const read = (file) => svgInner(readFileSync(join(svgDir, file), 'utf8'));
  const icons = manifest.icons.map((icon) => ({
    name: icon.name,
    component: icon.component,
    category: icon.category,
    svg: read(icon.file),
  }));
  const brands = manifest.brands.marks.map((mark) => ({
    name: mark.name,
    title: mark.title,
    component: mark.component,
    color: read(mark.files.color.md),
    mono: read(mark.files.mono.md),
  }));
  const json = (value) => JSON.stringify(value, null, 2);
  return `// Generated by \`node scripts/sync-icons.mjs <stuntkit checkout>\` from StuntKit's
// \`packages/icons/svg\`. Do not edit by hand.

export interface GalleryIcon {
  name: string;
  component: string;
  category: string;
  /** The elements inside the 24 unit \`<svg>\`, stroked in \`currentColor\`. */
  svg: string;
}

export interface GalleryBrand {
  name: string;
  title: string;
  component: string;
  /** The elements inside the 24 unit \`<svg>\`, in the brand's colours. */
  color: string;
  /** The same mark filled in \`currentColor\`. */
  mono: string;
}

export const ICON_CATEGORIES: string[] = ${json(manifest.categories)};

export const GALLERY_ICONS: GalleryIcon[] = ${json(icons)};

export const GALLERY_BRANDS: GalleryBrand[] = ${json(brands)};
`;
}

function main() {
  const checkout = process.argv[2];
  if (!checkout) {
    console.error('usage: node scripts/sync-icons.mjs <stuntkit checkout>');
    process.exit(1);
  }
  writeFileSync(OUT, buildModule(join(resolve(checkout), 'packages/icons/svg')));
  console.log(`wrote ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
